const POOL_FNS = ['addLiquidity', 'removeLiquidity', 'swap', 'reserves', 'base', 'quote']
/** Has Pool functions and reserves() returns two values. */
export const isPoolAbi = (abi: Abi): boolean => {
  const fns = abi.filter(e => e.type === 'function')
  return POOL_FNS.every(f => fns.some(e => e.name === f)) && fns.find(e => e.name === 'reserves')?.outputs.length === 2
}
