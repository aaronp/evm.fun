import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';
import {percentile, type RunResult} from '@evmb/core';
import {ROOT} from './approaches.ts';

const MARK = '<!-- notes -->';
const TARGET = 1000;
const med = (a: number[]) => percentile([...a].sort((x, y) => x - y), 50);
const fmt = (x: number) => Math.round(x).toLocaleString('en-US');
// row label: approach id plus its options, e.g. `02-seq-memory (block=2000)`
const label = (r: RunResult) => {
  const o = Object.entries(r.params.opts ?? {}).sort(([a], [b]) => a.localeCompare(b));
  return o.length ? `${r.approach.id} (${o.map(([k, v]) => `${k}=${v}`).join(', ')})` : r.approach.id;
};

export function renderReport(results: RunResult[], notes: string, excluded: RunResult[] = []): string {
  const newest = results.reduce((a, b) => (b.env.startedAt > a.env.startedAt ? b : a));
  const e = newest.env;
  const out = [
    '# EVM settlement benchmark report',
    '',
    `Generated by \`bun run report\`. Env (newest result): cpu ${e.cpu}, ${e.cores} cores, runtime ${e.runtime}, os ${e.os}. Engine is per approach (column \`engine\`). n=${newest.params.n}.`,
    '',
  ];
  if (excluded.length) {
    const byN = new Map<number, number>();
    for (const r of excluded) byN.set(r.params.n, (byN.get(r.params.n) ?? 0) + 1);
    out.push(`Excluded ${excluded.length} results with n≠${newest.params.n} (${[...byN].sort((a, b) => a[0] - b[0]).map(([n, c]) => `n=${n}: ${c}`).join(', ')})`, '');
  }
  for (const scenario of [...new Set(results.map((r) => r.scenario))].sort()) {
    const rs = results.filter((r) => r.scenario === scenario);
    const rows = [...new Set(rs.map(label))].map((id) => {
      const runs = rs.filter((r) => label(r) === id);
      const ok = runs.filter((r) => r.verified && r.tps !== null);
      const m = runs[0]!.approach;
      return {
        id,
        tps: ok.length ? med(ok.map((r) => r.tps!)) : null,
        line: (tps: string) => `| ${id} | ${m.engine ?? '—'} | ${tps} | ${fmt(med(runs.map((r) => r.latencyMs.p50)))} | ${fmt(med(runs.map((r) => r.latencyMs.p99)))} | ${runs.filter((r) => r.verified).length}/${runs.length} | ${runs.reduce((s, r) => s + r.statuses.reverted + r.statuses.rejected, 0)} | ${m.tradeoffs.evm ? 'yes' : 'no'} | ${m.tradeoffs.stateRoot} | ${m.tradeoffs.log} | ${m.tradeoffs.sigVerify} | ${m.tradeoffs.execution} |`,
      };
    }).sort((a, b) => (b.tps ?? -1) - (a.tps ?? -1));
    const met = rows.filter((r) => r.tps !== null && r.tps >= TARGET).map((r) => r.id);
    out.push(
      `## ${scenario}`,
      '',
      '| approach | engine | median TPS | p50 ms | p99 ms | runs (verified/total) | rejected/reverted | evm | stateRoot | log | sigVerify | execution |',
      '| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- | --- | --- | --- |',
      ...rows.map((r) => r.line(r.tps === null ? '—' : fmt(r.tps))),
      '',
      `Target: 1,000 TPS — ${met.length ? `✅ met by: ${met.join(', ')}` : '❌ not met'}`,
      '',
    );
  }
  return `${out.join('\n')}\n## Iteration log\n\n${MARK}\n${notes}`;
}

export function report(dir = process.env.RESULTS_DIR ?? join(ROOT, 'results'), out = join(ROOT, 'REPORT.md')) {
  const all = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')) as RunResult);
  if (!all.length) throw new Error(`no results in ${dir}`);
  // ponytail: only the largest n is reported, so smoke runs don't mix into medians
  const maxN = Math.max(...all.map((r) => r.params.n));
  const old = existsSync(out) ? readFileSync(out, 'utf8') : '';
  const i = old.indexOf(MARK);
  writeFileSync(out, renderReport(all.filter((r) => r.params.n === maxN), i < 0 ? '' : old.slice(i + MARK.length + 1), all.filter((r) => r.params.n !== maxN)));
  console.log(`Wrote ${out}`);
}
